def _anthropic_cfg() -> Dict[str, Any]:
    key = os.getenv("ANTHROPIC_API_KEY", "")
    if not key:
        raise RuntimeError("未设置 ANTHROPIC_API_KEY")
    cfg: Dict[str, Any] = {
        "api_key":  key,
        "model":    os.getenv("ANTHROPIC_MODEL", "claude-3-5-sonnet-20241022").strip(),
    }
    base_url = os.getenv("ANTHROPIC_BASE_URL", "").strip()
    if base_url:
        cfg["base_url"] = base_url
    return cfg


def _env_list(name: str, default: str) -> List[str]:
    """读取逗号分隔配置，忽略空项。"""
    return [item.strip() for item in os.getenv(name, default).split(",") if item.strip()]


def _env_bool(name: str, default: bool = False) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def _build_embedding_function():
    """构造 Intent 与 RAG 共用的本地多语言 Embedding。"""
    from core.embedding_provider import LocalSentenceTransformerEmbedding

    model = os.getenv("EMBEDDING_MODEL", "Qwen/Qwen3-Embedding-0.6B").strip()
    device = os.getenv("EMBEDDING_DEVICE", "cpu").strip()
    function = LocalSentenceTransformerEmbedding(
        model_name=model,
        device=device,
        query_prompt_name=os.getenv("EMBEDDING_QUERY_PROMPT", "query").strip(),
        query_instruction=os.getenv(
            "EMBEDDING_QUERY_INSTRUCTION",
            "Given an enterprise SaaS customer support request, retrieve the most relevant product documentation, account policy, billing rule, or troubleshooting passage that answers the request",
        ).strip(),
        normalize_embeddings=True,
    )
    return model, device, function


def _require_admin_key(
    provided_key: Optional[str] = Header(default=None, alias="X-RelayDesk-Admin-Key"),
) -> None:
    """保护会改变系统状态或触发高成本任务的管理接口。"""
    expected_key = os.getenv("RELAYDESK_ADMIN_KEY", "").strip()
    if not expected_key:
        raise HTTPException(503, "管理接口未配置 RELAYDESK_ADMIN_KEY")
    if not provided_key or not hmac.compare_digest(provided_key, expected_key):
        raise HTTPException(401, "管理密钥无效")


