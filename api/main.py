    # Intent 与 RAG 共用同一个本地中文 Embedding 实例，与 LLM Provider 解耦。
    embedding_model, embedding_device, embedding_function = _build_embedding_function()
    logger.info(f"Embedding: {embedding_model}  device: {embedding_device}")

