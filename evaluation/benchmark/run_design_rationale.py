async def tool_benchmark(output_dir: Path) -> List[Dict[str, Any]]:
    from mcp.tool_manager import CircuitBreaker, CircuitState, MCPToolManager, Tool

    schema = {"type": "object", "properties": {"query": {"type": "string"}}, "required": ["query"]}
    fallback = lambda params, context, error: {"fallback": True, "reason": error, "query": params.get("query")}

    async def timed(awaitable: Any) -> Tuple[float, Any, Optional[str]]:
        started = time.perf_counter()
        try:
            value = await awaitable
            return (round((time.perf_counter() - started) * 1000, 3), value, None)
        except Exception as exc:
            return (round((time.perf_counter() - started) * 1000, 3), None, type(exc).__name__)

    manager = MCPToolManager("benchmark-placeholder")
    scenarios: List[Dict[str, Any]] = []

    # Normal response.
    async def normal_handler(params: Dict[str, Any], context: Any) -> Dict[str, Any]:
        return {"ok": True, "query": params["query"]}
    base_ms, base_value, base_error = await timed(normal_handler({"query": "normal"}, None))
    normal_tool = Tool("normal", "Normal tool", normal_handler, schema, fallback=fallback)
    manager.register(normal_tool)
    cur_ms, cur_result, cur_error = await timed(manager.call("normal", {"query": "normal"}))
    scenarios.append({
        "scenario": "normal-response", "v0_latency_ms": base_ms, "v0_success": base_error is None,
        "current_latency_ms": cur_ms, "current_success": bool(cur_result and cur_result.success),
    })

    # Repeated parameters and cache behavior.
    base_calls = {"n": 0}
    async def counted_handler(params: Dict[str, Any], context: Any) -> Dict[str, Any]:
        base_calls["n"] += 1
        return {"sequence": base_calls["n"]}
    await counted_handler({"query": "repeated"}, None)
    await counted_handler({"query": "repeated"}, None)
    v0_invocations = base_calls["n"]
    current_calls = {"n": 0}
    async def cached_handler(params: Dict[str, Any], context: Any) -> Dict[str, Any]:
        current_calls["n"] += 1
        return {"sequence": current_calls["n"]}
    cache_tool = Tool("cache", "Cache tool", cached_handler, schema, cache_ttl=60, fallback=fallback)
    manager.register(cache_tool)
    first = await manager.call("cache", {"query": "repeated"})
    second = await manager.call("cache", {"query": "repeated"})
    scenarios.append({
        "scenario": "repeated-parameters", "v0_handler_invocations": v0_invocations,
        "current_handler_invocations": current_calls["n"], "second_call_cached": second.cached,
        "current_return_sequences": [first.data["sequence"], second.data["sequence"]],
    })

    # Slow request: V0 waits for completion; Current uses a shortened injected timeout.
    async def slow_handler(params: Dict[str, Any], context: Any) -> Dict[str, Any]:
        await asyncio.sleep(0.2)
        return {"ok": True}
    v0_ms, _, _ = await timed(slow_handler({"query": "slow"}, None))
    timeout_tool = Tool("timeout", "Timeout tool", slow_handler, schema, timeout_s=0.05, fallback=fallback)
    manager.register(timeout_tool)
    current_ms, timeout_result, _ = await timed(manager.call("timeout", {"query": "slow"}))
    scenarios.append({
        "scenario": "slow-request", "v0_latency_ms": v0_ms, "v0_waited_for_handler_completion": True,
        "current_latency_ms": current_ms, "current_returned_fallback": bool(timeout_result and timeout_result.data.get("fallback")),
        "injected_timeout_seconds": 0.05, "production_default_tool_timeout_seconds": 30.0,
    })

    # Never-ending request: the benchmark externally cancels V0; Current uses its native timeout.
    never_event = asyncio.Event()
    async def never_handler(params: Dict[str, Any], context: Any) -> None:
        await never_event.wait()
    v0_ms, _, v0_error = await timed(asyncio.wait_for(never_handler({"query": "blocked"}, None), timeout=0.05))
    never_tool = Tool("never", "Blocking tool", never_handler, schema, timeout_s=0.05, fallback=fallback)
    manager.register(never_tool)
    current_ms, never_result, _ = await timed(manager.call("never", {"query": "blocked"}))
    scenarios.append({
        "scenario": "never-ending-request", "v0_external_guard_latency_ms": v0_ms,
        "v0_native_protection": False, "v0_external_guard_result": v0_error,
        "current_latency_ms": current_ms, "current_native_timeout_and_fallback": bool(never_result and never_result.data.get("fallback")),
    })

    # Handler exception and fallback.
    async def error_handler(params: Dict[str, Any], context: Any) -> None:
        raise RuntimeError("injected failure")
    v0_ms, _, v0_error = await timed(error_handler({"query": "error"}, None))
    error_tool = Tool("error", "Exception tool", error_handler, schema, fallback=fallback)
    manager.register(error_tool)
    current_ms, error_result, _ = await timed(manager.call("error", {"query": "error"}))
    scenarios.append({
        "scenario": "handler-exception", "v0_latency_ms": v0_ms, "v0_exception_type": v0_error,
        "current_latency_ms": current_ms, "current_successful_wrapper": error_result.success,
        "current_returned_fallback": bool(error_result.data.get("fallback")),
    })

    # Consecutive failures, circuit opening, and recovery.
    breaker_calls = {"n": 0, "recover": False}
    async def breaker_handler(params: Dict[str, Any], context: Any) -> Dict[str, Any]:
        breaker_calls["n"] += 1
        if not breaker_calls["recover"]:
            raise RuntimeError("consecutive injected failure")
        return {"ok": True}
    breaker_tool = Tool("breaker", "Circuit-breaker tool", breaker_handler, schema, fallback=fallback)
    breaker_tool.breaker = CircuitBreaker(failure_threshold=5, recovery_s=0.05)
    manager.register(breaker_tool)
    first_five = [await manager.call("breaker", {"query": str(index)}, use_cache=False) for index in range(5)]
    calls_after_five = breaker_calls["n"]
    sixth = await manager.call("breaker", {"query": "sixth"}, use_cache=False)
    calls_after_sixth = breaker_calls["n"]
    state_after_sixth = breaker_tool.breaker.state.value
    await asyncio.sleep(0.06)
    breaker_calls["recover"] = True
    recovered = await manager.call("breaker", {"query": "recover"}, use_cache=False)
    scenarios.append({
        "scenario": "consecutive-failures-breaker-and-recovery", "first_five_returned_fallback": all(item.data.get("fallback") for item in first_five),
        "handler_calls_after_five": calls_after_five, "handler_calls_after_sixth": calls_after_sixth,
        "sixth_call_short_circuited": calls_after_sixth == calls_after_five and sixth.data.get("fallback"),
        "state_after_sixth": state_after_sixth, "recovery_probe_succeeded": recovered.success and recovered.data.get("ok"),
        "state_after_recovery": breaker_tool.breaker.state.value,
        "injected_recovery_seconds": 0.05, "production_default_breaker_failure_threshold": 5, "production_default_recovery_seconds": 60.0,
    })

    bad_cases = [
        {
            "id": "BC-TOOL-%03d" % (idx + 1), "feature": feature,
            "input_scenario": scenario["scenario"], "observed_bad_case": observed,
            "current_mechanism": mechanism, "measured_effect": effect,
        }
        for idx, (scenario, feature, observed, mechanism, effect) in enumerate([
            (scenarios[1], "Cache", "Calling the same parameters twice directly invokes the handler twice.", "TTL cache", "Handler invocations decreased from two to one."),
            (scenarios[2], "Timeout/Fallback", "A slow handler forces V0 to wait for full completion.", "asyncio timeout plus fallback", "The injected run returned a fallback in approximately 50 ms."),
            (scenarios[3], "Timeout/Fallback", "A never-ending handler has no native exit condition in V0.", "Native timeout plus fallback", "Current returned on its own; V0 required external benchmark cancellation."),
            (scenarios[4], "Fallback", "A handler exception propagates directly in V0.", "Exception wrapping plus fallback", "Current returned a structured fallback result."),
            (scenarios[5], "Circuit Breaker", "Persistent failures keep hitting the downstream handler in V0.", "OPEN after five failures and HALF_OPEN after recovery delay", "The sixth call did not invoke the handler; a successful recovery probe closed the circuit."),
        ])
    ]
    write_json(output_dir / "tool_reliability.json", envelope(
        "EXECUTED",
        "All fake-tool fault injections were executed. Shortened timeout and recovery values validate the state machine only; production defaults are recorded separately.",
        "V0 directly awaits the handler. Current uses the production MCPToolManager.call implementation without modifying the class.",
        {"scenarios": scenarios, "observed_bad_cases": bad_cases},
    ))
    return bad_cases


async def judge_benchmark(output_dir: Path, llm_probe: Dict[str, Any]) -> List[Dict[str, Any]]:
    from evaluation.evaluator import LLMJudge

    dataset = load_json(DATA_DIR / "judge_design_rationale.json")
    if not llm_probe.get("available"):
        write_json(output_dir / "judge_reliability.json", envelope(
            "NOT EXECUTED",
            "LLM probe failed: %s. The current Evaluator returns 0.5 with judge_failed=true on Judge failure; 0.5 must not be reported as a real Judge score." % llm_probe.get("reason"),
            "Stored controlled high-, medium-, and low-quality responses. Each response must be scored three times before variance and range are calculated.",
            {
                "dataset_sample_count": len(dataset["samples"]),
                "Relevance/Accuracy/Completeness/Helpfulness": "NOT EXECUTED",
                "repeated_score_variance": "NOT EXECUTED",
                "controlled_http_success_samples": dataset["samples"],
                "conclusion_boundary": "Judge is an automated regression signal, not absolute ground truth.",
            },
        ))
        return []

    _, _, model = llm_settings()
    tracker = tracked_llm_client(min_max_tokens=1024)
    judge = LLMJudge(tracker, model)
    semaphore = asyncio.Semaphore(4)
    repeats = 3

    async def score_once(sample: Dict[str, Any], quality: str, response: str, repeat: int) -> Dict[str, Any]:
        async with semaphore:
            started = time.perf_counter()
            scores = await judge.judge(
                sample["question"], response,
                context="Expected points: " + "; ".join(sample.get("expected_points", [])),
            )
            return {
                "sample_id": sample["id"], "quality": quality, "repeat": repeat,
                "relevance": scores.relevance, "accuracy": scores.accuracy,
                "completeness": scores.completeness, "helpfulness": scores.helpfulness,
                "overall": round(scores.overall, 4), "judge_failed": scores.judge_failed,
                "error": scores.error, "latency_ms": round((time.perf_counter() - started) * 1000, 3),
            }

    tasks = []
    for sample in dataset["samples"]:
        for quality, response in sample["response_variants"].items():
            for repeat in range(1, repeats + 1):
                tasks.append(score_once(sample, quality, response, repeat))
    rows = await asyncio.gather(*tasks)
    valid_rows = [row for row in rows if not row["judge_failed"]]
    grouped: Dict[Tuple[str, str], List[Dict[str, Any]]] = defaultdict(list)
    for row in valid_rows:
        grouped[(row["sample_id"], row["quality"])].append(row)

    per_sample: List[Dict[str, Any]] = []
    bad_cases: List[Dict[str, Any]] = []
    ordering_passes = 0
    ordering_evaluable = 0
    for sample in dataset["samples"]:
        summaries: Dict[str, Any] = {}
        for quality in ("high_quality", "medium_quality", "low_quality"):
            group = grouped.get((sample["id"], quality), [])
            overall = [row["overall"] for row in group]
            summaries[quality] = {
                "mean_overall": round(statistics.mean(overall), 4) if overall else None,
                "variance": round(statistics.pvariance(overall), 6) if len(overall) > 1 else 0.0 if overall else None,
                "score_range": round(max(overall) - min(overall), 4) if overall else None,
                "dimension_means": {
                    dimension: round(statistics.mean(row[dimension] for row in group), 4) if group else None
                    for dimension in ("relevance", "accuracy", "completeness", "helpfulness")
                },
                "runs": group,
            }
        high = summaries["high_quality"]["mean_overall"]
        medium = summaries["medium_quality"]["mean_overall"]
        low = summaries["low_quality"]["mean_overall"]
        ordered = bool(high is not None and medium is not None and low is not None and high > medium > low)
        evaluable = high is not None and medium is not None and low is not None
        ordering_evaluable += int(evaluable)
        ordering_passes += int(evaluable and ordered)
        per_sample.append({"id": sample["id"], "question": sample["question"], "quality_order_correct": ordered, "scores": summaries})
        if not evaluable or not ordered:
            bad_cases.append({
                "id": "BC-JUDGE-%03d" % (len(bad_cases) + 1), "feature": "LLM-as-Judge",
                "input": sample["question"], "expected_order": "high > medium > low",
                "observed_scores": {key: value["mean_overall"] for key, value in summaries.items()},
                "measured_effect": "Judge did not preserve the controlled quality ordering.",
            })

    aggregate: Dict[str, Any] = {}
    for quality in ("high_quality", "medium_quality", "low_quality"):
        quality_rows = [row for row in valid_rows if row["quality"] == quality]
        aggregate[quality] = {
            "mean_overall": round(statistics.mean(row["overall"] for row in quality_rows), 4) if quality_rows else None,
            "mean_dimensions": {
                dimension: round(statistics.mean(row[dimension] for row in quality_rows), 4) if quality_rows else None
                for dimension in ("relevance", "accuracy", "completeness", "helpfulness")
            },
        }
    write_json(output_dir / "judge_reliability.json", envelope(
        "EXECUTED" if len(valid_rows) == len(rows) else "PARTIALLY EXECUTED",
        "Repeated LLM-as-Judge scoring completed; failed calls are excluded rather than replaced by fallback 0.5 scores.",
        "Three controlled response qualities for each of three questions were scored three times with temperature 0. Expected points were supplied as evaluation context. The benchmark raises max_tokens to 1024 so the configured reasoning model can emit final JSON; production Evaluator remains at 256 and is reported as a compatibility limitation.",
        {
            "dataset_sample_count": len(dataset["samples"]),
            "repeat_count_per_response": repeats,
            "benchmark_max_tokens": 1024,
            "production_evaluator_max_tokens": 256,
            "successful_judge_calls": len(valid_rows), "failed_judge_calls": len(rows) - len(valid_rows),
            "quality_order_evaluable_sample_count": ordering_evaluable,
            "quality_order_accuracy": round(ordering_passes / ordering_evaluable, 4) if ordering_evaluable else None,
            "aggregate_quality_scores": aggregate,
            "per_sample_results": per_sample,
            "llm_usage": tracker.snapshot(),
            "observed_bad_cases": bad_cases,
            "conclusion_boundary": "Judge is an automated regression signal, not absolute ground truth.",
        },
    ))
    return bad_cases


def write_bad_cases(output_dir: Path, groups: Sequence[List[Dict[str, Any]]]) -> None:
    cases = [case for group in groups for case in group]
    by_feature: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for case in cases:
        by_feature[case.get("feature", "Intent Fusion")].append(case)
    write_json(output_dir / "bad_cases.json", envelope(
        "EXECUTED",
        "Includes observed cases only. No fabricated cases were added for unexecuted LLM ablations.",
        "Automatically aggregates the raw Intent, Direct RAG, Routing, Skills, and Tool results.",
        {"bad_case_count": len(cases), "by_feature": by_feature, "all_cases": cases},
    ))


async def main() -> None:
    parser = argparse.ArgumentParser(description="Run the RelayDesk Current Design Rationale Benchmark")
    parser.add_argument("--output-dir", default=str(DEFAULT_OUTPUT_DIR), help="Result output directory")
    args = parser.parse_args()
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    llm_probe = await probe_llm()
    intent_cases = await intent_benchmark(output_dir, llm_probe)
    rag_cases = await rag_benchmark(output_dir, llm_probe)
    routing_cases = await routing_benchmark(output_dir, llm_probe)
    memory_benchmark(output_dir, llm_probe)
    skill_cases = skills_benchmark(output_dir, llm_probe)
    tool_cases = await tool_benchmark(output_dir)
    judge_cases = await judge_benchmark(output_dir, llm_probe)
    write_bad_cases(output_dir, [intent_cases, rag_cases, routing_cases, skill_cases, tool_cases, judge_cases])

    print(json.dumps({
        "status": "benchmark-complete",
        "output_directory": str(output_dir),
        "llm_probe": llm_probe,
        "generated_files": sorted(path.name for path in output_dir.glob("*.json")),
    }, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    asyncio.run(main())
