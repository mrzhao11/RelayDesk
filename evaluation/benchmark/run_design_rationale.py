def load_json(path: Path) -> Dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def write_json(path: Path, payload: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
        handle.write("\n")


def git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=str(ROOT), text=True
        ).strip()
    except Exception:
        return "unavailable"


def percentile(values: Sequence[float], p: float) -> Optional[float]:
    if not values:
        return None
    ordered = sorted(values)
    if len(ordered) == 1:
        return round(ordered[0], 3)
    rank = (len(ordered) - 1) * p
    lower = math.floor(rank)
    upper = math.ceil(rank)
    if lower == upper:
        value = ordered[lower]
    else:
        value = ordered[lower] + (ordered[upper] - ordered[lower]) * (rank - lower)
    return round(value, 3)


def socket_state(host: str, port: int) -> str:
    sock = socket.socket()
    sock.settimeout(0.5)
    try:
        sock.connect((host, port))
        return "reachable"
    except PermissionError:
        return "socket probing blocked by the current sandbox"
    except Exception as exc:
        return "unreachable (%s)" % type(exc).__name__
    finally:
        sock.close()


def environment_snapshot() -> Dict[str, Any]:
    values = dotenv_values(ROOT / ".env") if (ROOT / ".env").exists() else {}
    base_url = values.get("ANTHROPIC_BASE_URL") or ""
    embedding_model = values.get("EMBEDDING_MODEL") or "Qwen/Qwen3-Embedding-0.6B"
